        out = ed.verify(ctx, ask, candidate, lambda: False)
        self.assertEqual(out['validation_status'], 'unknown')
        self.assertEqual(out['validation_reason'], 'investigation_budget_exhausted')
        self.assertEqual(len(out['verification_trace']), 6)
        self.assertEqual(ed.verify(ctx, ask, candidate, lambda: True)['validation_reason'], 'interrupted')

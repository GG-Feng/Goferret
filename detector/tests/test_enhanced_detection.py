        self.assertEqual(out['candidates'][0]['validation_reason'], 'entry unresolved')
        self.assertEqual(out['limits']['discovery_calls_used'], 1)
        self.assertEqual(out['limits']['verification_calls_used'], 1)
        self.assertEqual(out['tasks'][1]['reason'], 'model_call_budget_exhausted')

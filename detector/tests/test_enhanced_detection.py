    def test_bind_extractions_by_id_and_reject_invalid_batches(self):
        def row(k):
            return dict(function_id=k, purpose=k, semantic_inputs=[], semantic_sinks=[], observed_checks=[])
        rows, errors = ed.bind_extractions([row('b'), row('a')], ['a', 'b'])
        self.assertEqual(rows['a']['purpose'], 'a')
        self.assertFalse(errors)
        legacy = row('a')
        legacy['function'] = legacy.pop('function_id')
        rows, errors = ed.bind_extractions([legacy], ['a'])
        self.assertEqual(rows['a']['function_id'], 'a')
        self.assertFalse(errors)
        for data in ([row('a'), row('a')], [row('z')]):
            self.assertEqual(ed.bind_extractions(data, ['a', 'b'])[0], {})
        self.assertEqual(ed.bind_extractions([dict(legacy, function='other')], ['a'])[0], {})
        rows, errors = ed.bind_extractions([row('b')], ['a', 'b'])
        self.assertEqual(errors, [{'function_id': 'a', 'reason': 'missing_id'}])

    def test_verdict_needs_source_backed_claims(self):
        ctx, raw, candidate = self.sample()
        def answer(status, kinds, unresolved=None):
            return {'action': 'finish', 'candidate_id': candidate['finding_id'], 'status': status,
                    'reason': 'evidence', 'unresolved': unresolved or [],
                    'claims': [{'kind': k, 'statement': 'claim', 'references': raw['references']} for k in kinds]}
        for status, kinds, expected in [('supported', ['input'], 'unknown'),
                ('supported', ['input', 'operation', 'impact'], 'supported'),
                ('refuted', ['protection'], 'unknown'),
                ('refuted', ['operation', 'protection'], 'refuted'),
                ('refuted', [], 'unknown')]:
            response = answer(status, kinds)
            out = ed.verify(ctx, lambda *a: (response, None), candidate, lambda: False)
            self.assertEqual(out['validation_status'], expected)
            self.assertEqual(out['runtime_validation'], 'not_run')
        response = answer('supported', ['input', 'operation', 'impact'], ['entry unresolved'])
        self.assertEqual(ed.verify(ctx, lambda *a: (response, None), candidate, lambda: False)['validation_status'], 'unknown')
        response = answer('refuted', ['operation', 'protection'])
        response['claims'][0]['references'] = [ctx.reference('a.go', 2, 2)]
        self.assertEqual(ed.verify(ctx, lambda *a: (response, None), candidate, lambda: False)['validation_status'], 'unknown')
        response['claims'][0]['references'] = [{'file': 'a.go', 'start_line': 99, 'end_line': 99, 'snippet': 'fake'}]
        self.assertEqual(ed.verify(ctx, lambda *a: (response, None), candidate, lambda: False)['validation_status'], 'unknown')

    def test_queries_and_budget_failures_remain_unknown(self):
        ctx, raw, candidate = self.sample()

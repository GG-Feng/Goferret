    def test_optional_full_run_raw_call_log_redacts_credentials(self):
        response = type('Response', (), {
            'status_code': 200,
            'text': '{"echo":"test-secret"}',
            'json': lambda self: {'model': 'model', 'usage': {}, 'choices': [
                {'finish_reason': 'stop', 'message': {'content': '{}'}}]},
        })()
        with tempfile.TemporaryDirectory() as output:
            with patch.dict(os.environ, {'GOFORRET_LLM_RAW_DIR': output}):
                with patch.object(dv.requests, 'post', return_value=response):
                    result, error = dv.call_llm({'LLM_BASE_URL': 'https://example.invalid',
                        'LLM_API_KEY': 'test-secret', 'LLM_MODEL': 'model',
                        'LLM_PROVIDER': 'deepseek'}, 'system', 'source')
            self.assertEqual((result, error), ({}, None))
            files = list(Path(output).glob('*.json'))
            self.assertEqual(len(files), 1)
            self.assertNotIn('test-secret', files[0].read_text())
            record = json.loads(files[0].read_text())
            self.assertEqual(record['request']['messages'][1]['content'], 'source')
            self.assertEqual(record['request']['response_format'], {'type': 'json_object'})
            self.assertEqual(record['http_status'], 200)


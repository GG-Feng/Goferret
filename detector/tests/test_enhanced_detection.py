    def test_bounded_run_verifies_discovery_before_next_unit(self):
        self.write('first.go', 'package p\nfunc First(x string) { opaque(x) }\n')
        self.write('second.go', 'package p\nfunc Second() {}\n')
        ctx = self.ctx()
        first_id = next(fid for fid, f in ctx.functions.items() if f['name'] == 'First')
        units = [(uid, ref) for uid, ref in ctx.units() if ref['start_line'] == 2]
        self.assertEqual(len(units), 2)
        ctx.units = lambda: iter(units)
        candidate = {'function_id': first_id, 'category': 'other_security',
                     'title': 'Opaque operation', 'hypothesis': 'input reaches opaque',
                     'trigger': 'external x', 'impact': 'unknown security effect',
                     'input_path': 'x', 'references': [ctx.reference('first.go', 2, 2)],
                     'questions': []}
